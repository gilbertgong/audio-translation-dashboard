#!/usr/bin/env bash
# macOS setup (Apple Silicon; not yet tried on a real Mac): see INSTALL_MAC.md.
# Puts Homebrew's whisper-server and llama-server where the project expects
# its servers, and writes config_generated.toml for this Mac's memory (the
# launcher's Generate config needs nvidia-smi, so it can't do it here). Then
# run ./launch.sh as printed at the end. Safe to run again.

set -e
cd "$(dirname "$0")"

say() { printf '\n== %s\n' "$*"; }
fail() { printf '\nerror: %s\n' "$*" >&2; exit 1; }

[ "$(uname -s)" = Darwin ] || fail "this script is for macOS"
if [ "$(uname -m)" != arm64 ]; then
  echo "warning: this is not an Apple Silicon Mac ($(uname -m)): untested, and whisper and llama will be slow"
fi

# --- Python 3.11 or newer (PYTHON=... to choose one)
say "Python"
if [ -z "$PYTHON" ]; then
  for candidate in python3.12 python3.13 python3.11 python3; do
    if command -v "$candidate" >/dev/null && "$candidate" -c 'import sys; sys.exit(sys.version_info < (3, 11))' 2>/dev/null; then
      PYTHON="$candidate"
      break
    fi
  done
fi
[ -n "$PYTHON" ] || fail "no Python 3.11 or newer found. Install Python 3.12 from https://www.python.org/downloads/macos/ (recommended), then run this again"
PYTHON="$(command -v "$PYTHON")"
echo "$PYTHON ($("$PYTHON" --version 2>&1))"
"$PYTHON" -c 'import tkinter' 2>/dev/null || echo "note: no Tk in this Python: launch.sh works, the launcher window won't (see INSTALL_MAC.md)"
if ! "$PYTHON" -c 'import urllib.request; urllib.request.urlopen("https://huggingface.co", timeout=20)' 2>/dev/null; then
  fail "this Python can't open https://huggingface.co. No internet, or (python.org's Python) its certificates aren't installed yet: run \"Install Certificates.command\" in /Applications/Python 3.x/, then run this again"
fi

# --- whisper-server and llama-server from Homebrew (Metal builds)
say "Homebrew: whisper-cpp and llama.cpp"
command -v brew >/dev/null || fail "Homebrew not found: install it from https://brew.sh, then run this again"
BREW="$(brew --prefix)"
for formula in whisper-cpp llama.cpp; do
  if brew list "$formula" >/dev/null 2>&1; then
    echo "$formula: installed"
  else
    brew install "$formula"
  fi
done

# A server folder copied from Windows holds Windows builds; Kokoro's Python
# packages are per system too: they all have to be installed again here.
if find api_servers \( -name '*.exe' -o -name '*.dll' -o -name '*.pyd' \) 2>/dev/null | grep -q .; then
  fail "api_servers/ holds Windows files (copied from a PC?): delete everything in it except .gitkeep, then run this again"
fi

say "Linking the servers into api_servers/"
for pair in whisper:whisper-server llama:llama-server; do
  name="${pair%%:*}"
  program="${pair#*:}"
  exe="$BREW/bin/$program"
  [ -x "$exe" ] || fail "$exe not found. Homebrew's programs named like it: $(ls "$BREW/bin" | grep -i "${name}" | tr '\n' ' ')"
  mkdir -p "api_servers/$name"
  ln -sf "$exe" "api_servers/$name/$program"
  # The installer finds this and leaves the server alone (ensure_version = false).
  echo "homebrew" > "api_servers/$name/VERSION"
  echo "api_servers/$name/$program -> $exe"
done

# --- config_generated.toml, sized to this Mac's memory
say "Config"
if [ -f config_generated.toml ]; then
  echo "config_generated.toml exists: kept (delete it and run this again for a new one)"
else
  memory_gb=$(( $(sysctl -n hw.memsize) / 1073741824 ))
  if [ "$memory_gb" -ge 32 ]; then
    fragments="whisper_large-v3 llama_qwen3.8-27b-ud-iq3_xxs kokoro_v1.1"
  elif [ "$memory_gb" -ge 16 ]; then
    fragments="whisper_large-v3-q5_0 llama_qwen3.5-9b-ud-q3_k_xl kokoro_v1.1"
  else
    fragments="whisper_large-v3-turbo-q5_0 llama_qwen3.5-9b-ud-iq3_xxs kokoro_v1.1"
  fi
  {
    echo "# Generated by setup_mac.sh for a Mac with ${memory_gb} GB of memory:"
    echo "# $fragments (Qwen3-TTS off: no macOS build)"
    for fragment in $fragments; do
      printf '\n# --- fragment %s\n\n' "$fragment"
      cat "config/fragments/$fragment.toml"
    done
    printf '\n# --- off\n\n[api_servers.qwentts]\nstart = false\n'
  } > config_generated.toml
  "$PYTHON" -c 'import tomllib; tomllib.load(open("config_generated.toml", "rb"))' \
    || fail "config_generated.toml didn't come out as valid TOML"
  echo "${memory_gb} GB of memory: $fragments"
  echo "written to config_generated.toml (languages: English and Chinese unless you add a [languages] section)"
fi

say "Done. Next, from this folder:"
echo "  PYTHON=\"$PYTHON\" bash launch.sh"
echo "The first run installs Kokoro's packages and downloads the models (several GB), then opens"
echo "nothing by itself: open http://127.0.0.1:8080/ in Chrome. Ctrl+C stops everything."
